"""Reading order of the handbook pages, shared by the other scripts.

The order follows the links in the main README's "Where Everything Lives"
list, then each folder README's "Contents" or "Sections" list, depth first.
"""

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LINK = re.compile(r"^- \[[^\]]*\]\(([^)#\s]+)\)")
NAV_MARKER = "<!-- nav: generated by scripts/nav.py, do not edit below -->"


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def resolve(page, target):
    return os.path.normpath(os.path.join(os.path.dirname(page), target))


def section_links(page, headings):
    """Top-level list links under any of the given ## headings, in order."""
    links, inside = [], False
    for line in read(page).split("\n"):
        if line.startswith("## "):
            inside = line[3:].strip() in headings
        elif inside and LINK.match(line):
            links.append(resolve(page, LINK.match(line).group(1)))
    return links


def reading_order():
    """List of (path, depth) pairs, from the README to the last appendix."""
    order = [("README.md", 0), ("START_HERE.md", 0)]

    def visit(page, depth):
        order.append((page, depth))
        if os.path.basename(page) == "README.md":
            for child in section_links(page, ("Contents", "Sections")):
                visit(child, depth + 1)

    for part in section_links("README.md", ("Where Everything Lives",)):
        visit(part, 1)
    return order


def title(page):
    for line in read(page).split("\n"):
        if line.startswith("# "):
            return line[2:].strip()
    return os.path.basename(page)


def strip_nav(text):
    """The page text without its generated footer."""
    return text.split("\n" + NAV_MARKER)[0].rstrip("\n") + "\n"
